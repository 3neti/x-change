<?php

declare(strict_types=1);

it('documents the campaign recipient activity publish and browser verification', function (): void {
    $packageRoot = dirname(__DIR__, 3);
    $hostRoot = dirname($packageRoot, 2);
    $report = file_get_contents($packageRoot.'/docs/ui-cockpit/reports/281-wave-43d-campaign-recipient-activity-publish-browser-verification.md');
    $hostPanel = file_get_contents($hostRoot.'/resources/js/cockpit/components/CockpitOperatorIssuanceActivityPanel.vue');
    $hostTypes = file_get_contents($hostRoot.'/resources/js/cockpit/types.ts');
    $cockpitCompass = file_get_contents($packageRoot.'/docs/ui-cockpit/COMPASS.md');
    $settlementCompass = file_get_contents($packageRoot.'/docs/architecture/SETTLEMENT_OS_COMPASS.md');

    expect($report)
        ->toContain('Cockpit Wave 43D')
        ->toContain('checked 58, ok 58, stale 0, missing 0, extra 0')
        ->toContain('npm run test:browser -- tests/playwright/cockpit-quick-generate-campaign-context.spec.ts')
        ->toContain('Campaign attribution')
        ->toContain('Cockpit Wave 43E — Campaign Recipient Issuance Activity Attribution Closure');

    expect($hostPanel)
        ->toContain('AUTO-GENERATED BY x-change:install')
        ->toContain('Do not edit this published host copy directly')
        ->toContain('cockpit-operator-issuance-activity-campaign-attribution');

    expect($hostTypes)
        ->toContain('AUTO-GENERATED BY x-change:install')
        ->toContain('campaign_attribution');

    expect($cockpitCompass)
        ->toContain('Cockpit Wave 43D result: Campaign Recipient Activity publish/browser verification completed');

    expect($settlementCompass)
        ->toContain('Cockpit Wave 43D — Campaign Recipient Activity Publish / Browser Verification');
});
