<?php

declare(strict_types=1);

it('documents campaign destination context copy publish browser verification', function (): void {
    $packageRoot = dirname(__DIR__, 3);
    $hostRoot = dirname($packageRoot, 2);
    $report = file_get_contents($packageRoot.'/docs/ui-cockpit/reports/307-wave-48d-campaign-destination-context-copy-publish-browser-verification.md');
    $playwright = file_get_contents($hostRoot.'/tests/playwright/cockpit-campaign-activity-navigation.spec.ts');
    $hostDetail = file_get_contents($hostRoot.'/resources/js/cockpit/pages/VoucherDetail.vue');
    $hostDistribution = file_get_contents($hostRoot.'/resources/js/cockpit/pages/DistributionWorkspace.vue');
    $cockpitCompass = file_get_contents($packageRoot.'/docs/ui-cockpit/COMPASS.md');
    $settlementCompass = file_get_contents($packageRoot.'/docs/architecture/SETTLEMENT_OS_COMPASS.md');

    expect($report)
        ->toContain('Cockpit Wave 48D')
        ->toContain('Completed')
        ->toContain('Opened from campaign activity')
        ->toContain('Inspecting distribution from campaign activity');

    expect($playwright)
        ->toContain('Opened from campaign activity')
        ->toContain('Back to Explorer')
        ->toContain('Inspecting distribution from campaign activity');

    expect($hostDetail)
        ->toContain('AUTO-GENERATED BY x-change:install')
        ->toContain('Opened from campaign activity');

    expect($hostDistribution)
        ->toContain('AUTO-GENERATED BY x-change:install')
        ->toContain('Inspecting distribution from campaign activity');

    expect($cockpitCompass)
        ->toContain('Cockpit Wave 48D result: Campaign destination context copy publish/browser verification completed')
        ->toContain('Cockpit Wave 48E — Campaign Recipient Destination Context Copy Closure');

    expect($settlementCompass)
        ->toContain('Cockpit Wave 48D — Campaign Destination Context Copy Publish / Browser Verification')
        ->toContain('Cockpit Wave 48E — Campaign Recipient Destination Context Copy Closure');
});
